#!/usr/bin/env python3
"""Prepare the paper figures from the supplied CSVs without changing the inputs.

All rows and missing values are retained. Plot-specific transformations are
recorded here; numerical reductions live in analysis/ and example-analysis.json.
Only the Python standard library is needed.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import importlib.util
import io
import json
import math
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "analysis"))

from _common import (  # noqa: E402
    ALBEDO_DARK_S,
    ALBEDO_REFERENCE_S,
    MARS_BASELINE_S,
    PRESSURE_BASELINE_S,
    TRANSIT_BASELINE_OFFSET_S,
    in_window,
    read_table,
)

REPOSITORY_DATA = HERE.parents[1] / "example-data"
DATA_ROOT = HERE / "example-data" if (HERE / "example-data").is_dir() else REPOSITORY_DATA
COLORS = ("csblue", "csred", "csteal", "csgold")
STYLES = ("solid", "dashed", "dashdotted", "densely dotted")


def read_csv(path: Path) -> tuple[list[str], list[list[float]]]:
    headers, rows = read_table(path)
    if any(b[0] <= a[0] for a, b in zip(rows, rows[1:])):
        raise ValueError(f"Time is not strictly increasing: {path}")
    return headers, rows


def table_text(rows: list[list[float]]) -> str:
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow([f"c{i}" for i in range(len(rows[0]))])
    writer.writerows([[format(value, ".12g") for value in row] for row in rows])
    return stream.getvalue()


def window_mean(rows: list[list[float]], column: int, start: float, stop: float) -> float:
    return statistics.mean(row[column] for row in rows if in_window(row[0], start, stop))


def series(
    file: str,
    column: int,
    label: str,
    color: int = 0,
    *,
    x: int = 0,
    scale: float = 1,
    offset: float = 0,
    options: str = "",
) -> dict:
    return dict(
        file=file,
        column=column,
        label=label,
        color=color,
        x=x,
        scale=scale,
        offset=offset,
        options=options,
    )


def panel(ylabel: str, curves: list[dict], *, options: str = "", title: str = "") -> dict:
    return dict(ylabel=ylabel, curves=curves, options=options, title=title)


def plot_source(panels: list[dict], xlabel: str = "Time (s)", height: str = "3.5cm") -> str:
    lines = [
        "% Generated by prepare_examples.py from the supplied CSV files.",
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[group style={group size=1 by "
        + str(len(panels))
        + r",vertical sep=1.15cm},",
        r"width=0.98\columnwidth,height=" + height + ",",
        r"grid=major,enlarge x limits=false,",
        r"legend style={font=\scriptsize,at={(0.5,1.03)},anchor=south,",
        r"legend columns=4,draw=none,fill=none,column sep=4pt},",
        r"title style={font=\scriptsize,at={(0.02,0.98)},anchor=north west,",
        r"fill=white,fill opacity=0.9,text opacity=1,inner sep=2pt},",
        r"ylabel style={font=\footnotesize},",
        r"xlabel style={font=\footnotesize},tick label style={font=\scriptsize}]",
    ]
    for index, item in enumerate(panels):
        axis = [f"ylabel={{{item['ylabel']}}}", item["options"]]
        if index == len(panels) - 1:
            axis.append(f"xlabel={{{xlabel}}}")
        if item["title"]:
            axis.append(f"title={{({chr(97 + index)}) {item['title']}}}")
        lines.append(r"\nextgroupplot[" + ",".join(x for x in axis if x) + "]")
        for curve in item["curves"]:
            number = curve["color"]
            style = f"{COLORS[number]},{STYLES[number]},line width=0.8pt"
            if curve["options"]:
                style += "," + curve["options"]
            expression = (
                f"(\\thisrow{{c{curve['column']}}}-({curve['offset']:.12g}))"
                f"*({curve['scale']:.12g})"
            )
            lines.append(
                r"\addplot["
                + style
                + "] table[col sep=comma,x=c"
                + str(curve["x"])
                + ",y expr={"
                + expression
                + "}] {data/"
                + curve["file"]
                + ".csv};"
            )
            if curve["label"]:
                lines.append(r"\addlegendentry{" + curve["label"] + "}")
        for xpos, low, high in item.get("events", []):
            lines.append(
                rf"\draw[black!40,densely dashed] (axis cs:{xpos},{low})"
                rf" -- (axis cs:{xpos},{high});"
            )
    lines.extend([r"\end{groupplot}", r"\end{tikzpicture}", ""])
    return "\n".join(lines)


def source_csvs() -> list[Path]:
    paths = sorted(DATA_ROOT.glob("astronomy/*.example.csv"))
    return paths + sorted(DATA_ROOT.glob("core/*.example.csv"))


def products() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    records: dict[str, list[list[float]]] = {}
    provenance = {}
    # The draft collection is separate from the fifteen-paper source set.
    for path in source_csvs():
        headers, rows = read_csv(path)
        name = path.name.removesuffix(".example.csv")
        records[name] = rows
        outputs[Path("data") / f"{name}.csv"] = table_text(rows)
        provenance[str(path.relative_to(DATA_ROOT))] = {
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "rows": len(rows),
            "columns": headers,
            "missing_cells": sum(math.isnan(value) for row in rows for value in row),
        }
    if len(records) != 21:
        raise ValueError(f"Expected 21 source CSVs, found {len(records)}")

    def add(slug: str, panels: list[dict], xlabel: str = "Time (s)", height: str = "3.5cm"):
        outputs[Path("figures") / f"{slug}.tex"] = plot_source(panels, xlabel, height)

    for slug, prefix, unit in (
        ("accelerometer", "Specific force", r"$\mathrm{m\,s^{-2}}$"),
        ("gyroscope", "Angular velocity", r"$\mathrm{deg\,s^{-1}}$"),
        ("magnetometer", "Magnetic field", r"$\mu\mathrm{T}$"),
    ):
        name = slug + "_plot_v1-2"
        first = 5 if slug == "accelerometer" else 1
        magnitude = 8 if slug == "accelerometer" else 4
        add(
            slug,
            [
                panel(
                    f"Components ({unit})",
                    [
                        series(name, i + first, axis, i)
                        for i, axis in enumerate(("$x$", "$y$", "$z$"))
                    ],
                    title=prefix,
                ),
                panel(
                    f"Magnitude ({unit})",
                    [series(name, magnitude, "", 0)],
                    title="Vector magnitude",
                ),
            ],
        )

    name = "pressure_plot_v1-2"
    p0 = window_mean(records[name], 2, *PRESSURE_BASELINE_S)
    add(
        "pressure",
        [
            panel("Pressure (hPa)", [series(name, 2, "")], title="Full record"),
            panel(
                r"$p-p_0$ (hPa)",
                [series(name, 2, "", offset=p0)],
                options="xmin=0,xmax=100,ymin=-0.45,ymax=0.15",
                title="Height changes",
            ),
        ],
    )
    name = "temperature_plot_v1-2"
    add(
        "temperature-humidity",
        [
            panel(r"Temperature ($^\circ$C)", [series(name, 1, "")], title="Sensor temperature"),
            panel("Relative humidity (\\%)", [series(name, 2, "", 2)], title="Humidity response"),
        ],
    )
    name = "light_plot_v1-2"
    add(
        "light-rgb",
        [
            panel(
                r"Counts ($10^3$)", [series(name, 1, "Clear", scale=0.001)], title="Clear channel"
            ),
            panel(
                r"Counts ($10^3$)",
                [
                    series(name, 2, "Red", 1, scale=0.001),
                    series(name, 3, "Green", 2, scale=0.001),
                    series(name, 4, "Blue", 0, scale=0.001),
                ],
                title="Colour channels",
            ),
        ],
    )
    name = "analog_input_plot_v1-2"
    add(
        "analog-inputs",
        [
            panel(
                "Display voltage (V)",
                [series(name, i + 4, f"A{i}", i, scale=0.001) for i in range(3)],
                title="Three input channels",
            ),
            panel(
                "A2 display (V)",
                [series(name, 6, "", 2, scale=0.001)],
                options="xmin=5,xmax=11,ymin=0,ymax=3.1",
                title="RC charging response",
            ),
        ],
    )

    curves = []
    for i, kind in enumerate(("sensortag", "phone")):
        name = "albedo_" + kind
        rows = records[name]
        dark = statistics.mean(
            row[1] for row in rows if any(in_window(row[0], *bounds) for bounds in ALBEDO_DARK_S)
        )
        white = window_mean(rows, 1, *ALBEDO_REFERENCE_S)
        curves.append(
            series(name, 1, ("SensorTag", "Phone")[i], i, scale=1 / (white - dark), offset=dark)
        )
    add(
        "albedo",
        [
            panel(
                "Relative response",
                curves,
                options="ymin=-0.07,ymax=1.15",
                title="Dark-subtracted reference ratio",
            )
        ],
        height="5.7cm",
    )

    name = "greenhouse"
    rows = records[name]
    difference0 = statistics.mean(row[2] - row[1] for row in rows if 0 <= row[0] < 1)
    difference = [[row[0], (row[2] - row[1]) - difference0] for row in rows]
    outputs[Path("data/greenhouse-difference.csv")] = table_text(difference)
    heat = [
        panel(
            r"Temperature ($^\circ$C)",
            [series(name, 1, "Open"), series(name, 2, "Covered", 1)],
            options="ymin=22,ymax=32",
            title="Sensor temperatures",
        ),
        panel(
            r"Adjusted difference (K)",
            [series("greenhouse-difference", 1, "", 2)],
            options="ymin=-0.2,ymax=4.5",
            title="Covered minus open",
        ),
    ]
    heat[0]["events"] = [(1, 22, 32), (6, 22, 32)]
    heat[1]["events"] = [(1, -0.2, 4.5), (6, -0.2, 4.5)]
    add("greenhouse", heat, "Time (min)")

    name = "ir-dist_habitable"
    rows = records[name]
    for kind, predicate in (("outward", lambda t: t < 21), ("return", lambda t: t >= 21)):
        outputs[Path("data") / f"ir-{kind}.csv"] = table_text(
            [[row[1], row[2]] for row in rows if predicate(row[0])]
        )
    add(
        "ir-distance",
        [
            panel(
                r"Temperature ($^\circ$C)",
                [
                    series("ir-outward", 1, "Outward", options="mark=*,mark size=0.7pt"),
                    series("ir-return", 1, "Return", 1, options="mark=square*,mark size=0.7pt"),
                    series(name, 3, "Die", 3, x=1, options="draw=csgray,densely dashed"),
                ],
                title="Object-temperature indication",
            ),
        ],
        "Mouse displacement (counts)",
        "5.7cm",
    )

    curves = []
    for i, kind in enumerate(("sensortag", "phone")):
        name = "missiontomars_" + kind
        curves.append(
            series(
                name,
                1,
                ("SensorTag", "Phone")[i],
                i,
                offset=window_mean(records[name], 1, *MARS_BASELINE_S),
            )
        )
    add(
        "mission-to-mars",
        [
            panel("Excess pressure (hPa)", curves, title="Independent acquisition paths"),
            panel(
                "Excess pressure (hPa)",
                [dict(curve, label="") for curve in curves],
                options="xmin=30,xmax=55,ymin=33.4,ymax=35.1",
                title="Pressure decay",
            ),
        ],
    )
    name = "owon_digital_multimeter-debug"
    add(
        "owon-interface",
        [
            panel(
                "Voltage (V)",
                [series(name, 1, "Decoded voltage", options="mark=*,mark size=0.7pt")],
                title="DC staircase",
            ),
        ],
        height="5.7cm",
    )

    name = "pt-star"
    add(
        "pt-star",
        [
            panel("Pressure (hPa)", [series(name, 1, "")], title="Chamber pressure"),
            panel(
                r"Die temperature ($^\circ$C)", [series(name, 2, "", 1)], title="Sensor temperature"
            ),
        ],
        "Time (min)",
    )
    tide = [
        panel(
            "Illuminance (lx)",
            [
                series("tidal-locking_opt3001", 1, "Day"),
                series("tidal-locking_opt3001", 2, "Night", 1),
            ],
            options="xmin=0,xmax=300,ymode=log,ymin=1,ymax=20000,ytick={1,100,10000}",
            title="Optical forcing",
        ),
        panel(
            r"Object ($^\circ$C)",
            [
                series("tidal-locking_tmp007", 2, "", 0),
                series("tidal-locking_tmp007", 4, "", 1),
            ],
            options="xmin=0,xmax=300,ymin=22,ymax=48",
            title="Infrared indication",
        ),
        panel(
            r"Die ($^\circ$C)",
            [
                series("tidal-locking_bmp280", 1, "", 0),
                series("tidal-locking_bmp280", 2, "", 1),
            ],
            options="xmin=0,xmax=300,ymin=22,ymax=42",
            title="Barometer temperature",
        ),
    ]
    for item, bounds in zip(tide, ((1, 20000), (22, 48), (22, 42)), strict=True):
        item["events"] = [(30, *bounds), (210, *bounds)]
    add("tidal-locking", tide, height="3.2cm")

    curves = []
    for i, kind in enumerate(("sensortag", "phone", "owon")):
        name = "transitmethode_" + kind
        baseline = statistics.mean(
            row[1]
            for row in records[name]
            if in_window(abs(row[0] - 22), *TRANSIT_BASELINE_OFFSET_S)
        )
        curves.append(series(name, 1, ("SensorTag", "Phone", "Owon")[i], i, scale=1 / baseline))
    add(
        "transit-method",
        [
            panel("Signal / baseline", curves, title="Three-event record"),
            panel(
                "Signal / baseline",
                [dict(curve, label="", options="mark=*,mark size=0.9pt") for curve in curves],
                options="xmin=18,xmax=26,ymin=0.95,ymax=1.015",
                title="First transit and sampling",
            ),
        ],
    )

    metrics = {}
    analysis_notes = {}
    for path in sorted((HERE / "analysis").glob("*.py")):
        if path.name.startswith(("_", "draft_", "revision_")):
            continue
        spec = importlib.util.spec_from_file_location(path.stem, path)
        if spec is None or spec.loader is None:
            raise ValueError(f"Cannot load analysis: {path}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        result = module.analyze(DATA_ROOT)
        if "window_convention" in result:
            analysis_notes[path.stem] = result.pop("window_convention")
        if metrics.keys() & result.keys():
            raise ValueError(f"Duplicate analysis: {path}")
        metrics.update(result)
    outputs[Path("example-analysis.json")] = (
        json.dumps(
            {"inputs": provenance, "analysis_notes": analysis_notes, "metrics": metrics},
            indent=2,
            ensure_ascii=False,
            allow_nan=False,
        )
        + "\n"
    )
    return outputs


def prepare(*, check: bool = False) -> None:
    outputs = products()
    for relative, text in outputs.items():
        target = HERE / relative
        if check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                raise ValueError(f"Stale paper analysis or figure: {relative}")
        else:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    figures = sum(relative.parts[0] == "figures" for relative in outputs)
    print(
        f"{'Checked' if check else 'Prepared'} {len(source_csvs())} CSV sources"
        f" and {figures} data figures."
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    prepare(check=args.check)
