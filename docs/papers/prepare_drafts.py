#!/usr/bin/env python3
"""Prepare draft-paper data and analyses, preserving all input rows and clocks.

The original fifteen-paper reductions remain in prepare_examples.py. This
module also prepares supplementary reductions for revisions of those papers.
Only the Python standard library is needed; --check never writes outputs.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "analysis"))

from _common import read_table  # noqa: E402
from prepare_examples import DATA_ROOT, HERE, plot_source, table_text  # noqa: E402
from publication import load_manifest  # noqa: E402


def read_csv(path: Path) -> tuple[list[str], list[list[float]]]:
    """Read numeric columns without assuming the first column is a clock."""
    headers, rows = read_table(path)
    if any(math.isinf(value) for row in rows for value in row):
        raise ValueError(f"Infinite CSV value: {path}")
    return headers, rows


def normalized_figure(specification: dict) -> str:
    panels = []
    for panel in specification["panels"]:
        curves = []
        for curve in panel["curves"]:
            defaults = dict(label="", color=0, x=0, scale=1, offset=0, options="")
            defaults.update(curve)
            curves.append(defaults)
        normalized = {"options": "", "title": "", **panel, "curves": curves}
        panels.append(normalized)
    source = plot_source(
        panels,
        specification.get("xlabel", "Time (s)"),
        specification.get("height", "3.5cm"),
    )
    return source.replace(
        "% Generated by prepare_examples.py", "% Generated by prepare_drafts.py", 1
    )


def products() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    provenance = {}
    source_paths = sorted((DATA_ROOT / "drafts").glob("*.example.csv"))
    if len(source_paths) != 37:
        raise ValueError(f"Expected 37 draft CSV sources, found {len(source_paths)}")
    for path in source_paths:
        headers, rows = read_csv(path)
        name = path.name.removesuffix(".example.csv")
        outputs[Path("data/drafts") / f"{name}.csv"] = table_text(rows)
        provenance[str(path.relative_to(DATA_ROOT))] = {
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "rows": len(rows),
            "columns": headers,
            "missing_cells": sum(math.isnan(value) for row in rows for value in row),
        }
    index = json.loads((DATA_ROOT / "drafts/manifest.json").read_text(encoding="utf-8"))
    draft_data = {}
    for item in index["datasets"]:
        draft_data.setdefault(Path(item["experiment"]).stem, []).append(item["file"])
    sources = load_manifest(HERE / "manifest.json")["analysis_sources"]
    all_data = {
        paper["slug"]: list(dict.fromkeys(paper["datasets"] + paper.get("related_datasets", [])))
        for paper in sources
    }
    for prefix, report_name in (
        ("draft_", "draft-analysis.json"),
        ("revision_", "revision-analysis.json"),
    ):
        metrics = {}
        modules = {}
        figures = {}
        derived = {}
        for path in sorted((HERE / "analysis").glob(f"{prefix}*.py")):
            spec = importlib.util.spec_from_file_location(path.stem, path)
            if spec is None or spec.loader is None:
                raise ValueError(f"Cannot load analysis: {path}")
            module = importlib.util.module_from_spec(spec)
            sys.modules[path.stem] = module
            spec.loader.exec_module(module)
            result = module.analyze(DATA_ROOT)
            if metrics.keys() & result.keys():
                raise ValueError(f"Duplicate analysis: {path}")
            metrics.update(result)
            module_hash = hashlib.sha256(path.read_bytes()).hexdigest()
            for slug in result:
                modules[slug] = {"file": f"analysis/{path.name}", "sha256": module_hash}
            if hasattr(module, "tables"):
                for name, rows in module.tables(DATA_ROOT).items():
                    relative = Path("data") / f"{name}.csv"
                    if relative.is_absolute() or ".." in relative.parts:
                        raise ValueError(f"Invalid derived table path: {name}")
                    if relative in outputs:
                        raise ValueError(f"Duplicate derived table: {name}")
                    if not rows or not rows[0] or any(len(row) != len(rows[0]) for row in rows):
                        raise ValueError(f"Invalid derived table shape: {name}")
                    outputs[relative] = table_text(rows)
                    derived[str(relative)] = hashlib.sha256(outputs[relative].encode()).hexdigest()
            if hasattr(module, "figures"):
                for slug, figure in module.figures().items():
                    if prefix == "revision_" and not slug.startswith("revision-"):
                        raise ValueError(f"Supplementary figure must use revision- prefix: {slug}")
                    relative = Path("figures") / f"{slug}.tex"
                    if relative.is_absolute() or ".." in relative.parts or relative in outputs:
                        raise ValueError(f"Invalid or duplicate figure: {slug}")
                    outputs[relative] = normalized_figure(figure)
                    figures[str(relative)] = hashlib.sha256(outputs[relative].encode()).hexdigest()
        paper_provenance = {}
        for slug in metrics:
            inputs = {}
            for name in all_data.get(slug, draft_data.get(slug, [])):
                path = DATA_ROOT / name
                if name in provenance:
                    inputs[name] = provenance[name]
                else:
                    headers, rows = read_csv(path)
                    inputs[name] = {
                        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                        "rows": len(rows),
                        "columns": headers,
                        "missing_cells": sum(math.isnan(value) for row in rows for value in row),
                    }
            paper_provenance[slug] = {"inputs": inputs, "analysis": modules[slug]}
        report = {
            "inputs": provenance if prefix == "draft_" else {},
            "papers": paper_provenance,
            "metrics": metrics,
            "generated_figures_sha256": figures,
            "derived_tables_sha256": derived,
        }
        outputs[Path(report_name)] = (
            json.dumps(report, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
        )
    return outputs


def prepare(*, check: bool = False) -> None:
    outputs = products()
    stale = []
    for relative, text in outputs.items():
        target = HERE / relative
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            if check:
                stale.append(str(relative))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    if stale:
        raise ValueError("Stale draft analysis outputs: " + ", ".join(stale))
    sources = len(list((DATA_ROOT / "drafts").glob("*.example.csv")))
    print(
        f"{'Checked' if check else 'Prepared'} {sources} draft CSV sources"
        " and supplementary analyses."
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    prepare(check=parser.parse_args().check)
